"""Guard against the frontend and backend chain registries drifting apart.

The frontend keeps its own copy of the chain config so it can render
instantly without waiting for an API call. That duplication is a deliberate
trade-off -- and this test is the price of it.

A mismatched chain ID or decimal count is a financial safety bug: the wrong
chain ID sends a transaction to the wrong network, and the wrong decimals
misreport every balance by a factor of ten. So we parse the TypeScript file
and compare it field by field against the Python registry.

If this test fails, the two files disagree. Fix the mismatch; do not relax
the test.
"""

import re
from pathlib import Path

import pytest

from app.blockchain.registry import CHAINS

FRONTEND_CHAINS = (
    Path(__file__).resolve().parents[2] / "frontend" / "src" / "config" / "chains.ts"
)


def _parse_frontend_chains() -> dict[str, dict[str, str]]:
    """Extract each chain object from the TypeScript config.

    A light regex parse is enough here: the file is generated by us, has a
    fixed shape, and the test fails loudly if that shape changes.
    """
    source = FRONTEND_CHAINS.read_text(encoding="utf-8")

    registry_match = re.search(
        r"export const CHAINS: Record<string, ChainConfig> = \{(.*?)\n\}",
        source,
        re.DOTALL,
    )
    assert registry_match, "Could not find the CHAINS object in chains.ts"

    chains: dict[str, dict[str, str]] = {}
    for block in re.finditer(r"(\w+):\s*\{(.*?)\n  \}", registry_match.group(1), re.DOTALL):
        key, body = block.group(1), block.group(2)
        fields = dict(re.findall(r"(\w+):\s*('[^']*'|\"[^\"]*\"|[\w.-]+)", body))
        chains[key] = {k: v.strip("'\"") for k, v in fields.items()}

    return chains


@pytest.fixture(scope="module")
def frontend_chains() -> dict[str, dict[str, str]]:
    assert FRONTEND_CHAINS.exists(), f"Frontend chain config not found at {FRONTEND_CHAINS}"
    return _parse_frontend_chains()


def test_both_registries_list_the_same_chains(frontend_chains) -> None:
    assert set(frontend_chains) == set(CHAINS)


@pytest.mark.parametrize("chain_key", sorted(CHAINS))
def test_chain_ids_match(chain_key: str, frontend_chains) -> None:
    """A wrong chain ID would target the wrong network."""
    backend = CHAINS[chain_key]
    frontend = frontend_chains[chain_key]

    expected = "null" if backend.chain_id is None else str(backend.chain_id)
    assert frontend["chainId"] == expected, (
        f"{chain_key}: frontend chainId {frontend['chainId']} != backend {expected}"
    )


@pytest.mark.parametrize("chain_key", sorted(CHAINS))
def test_native_decimals_match(chain_key: str, frontend_chains) -> None:
    """Wrong decimals misreport every balance by a power of ten."""
    backend = CHAINS[chain_key]
    frontend = frontend_chains[chain_key]

    assert frontend["nativeDecimals"] == str(backend.native_decimals)


@pytest.mark.parametrize("chain_key", sorted(CHAINS))
def test_native_symbol_and_family_match(chain_key: str, frontend_chains) -> None:
    backend = CHAINS[chain_key]
    frontend = frontend_chains[chain_key]

    assert frontend["nativeSymbol"] == backend.native_symbol
    assert frontend["family"] == backend.family.value


@pytest.mark.parametrize("chain_key", sorted(CHAINS))
def test_testnet_and_active_flags_match(chain_key: str, frontend_chains) -> None:
    """If one side thinks a chain is live and the other does not, the UI lies."""
    backend = CHAINS[chain_key]
    frontend = frontend_chains[chain_key]

    assert frontend["isTestnet"] == str(backend.is_testnet).lower()
    assert frontend["isActive"] == str(backend.is_active).lower()
